#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Regenerate dict/thuocl.dict.yaml from the vendored THUOCL word list.

THUOCL (THUNLP, MIT) ships `word<TAB>corpus frequency` rows for eleven domains
and no readings, so the pinyin column here is generated by pypinyin at the
version pinned in sources.lock. The word list itself is vendored verbatim under
tools/thuocl-src/ (pin + provenance in sources.lock), which keeps this generator
offline and reproducible -- the same rule convert_dict.py and upgrade_essay.py
follow.

Contract:
  * pure-CJK words of at least MIN_LENGTH characters only. THUOCL is a corpus
    harvest: its 2-3 character rows include name and administrative fragments
    (一公司, 内都, 源通, 向县). Imported unfiltered they outrank existing common
    words, because a corpus frequency is far larger than the essay weight the
    same candidate carries -- measured on this dictionary: `guohou` 果后 beat
    过后, `yuantong` 源通 beat 圆通, `neidou` 内都 beat 内斗. At four characters
    every one of those regressions goes away while the terms worth having
    (非公经济, 小尾寒羊, 内存泄露, 失血性休克, 问渠哪得清如许) stay.
  * drop words the shipped luna_pinyin.dict.yaml or essay.txt already carry.
    Those are already reachable -- essay feeds candidates through
    use_preset_vocabulary -- so a second copy only re-weights them.
  * keep THUOCL's corpus frequency as the weight (clamped to >= 1, the file has
    zero-frequency rows). It is the only frequency evidence this list has, and
    ranking by it inside a same-code group is what makes the imported terms
    land above the engine's character-composition guesses.
  * sort by (-weight, word) so regeneration is byte-stable; THUOCL itself is
    frequency-ordered but ties are not stable in the source files.
  * syllables come from pypinyin with the same convention as the luna base:
    toneless, `nv`/`lv`/`lve`/`nve` for ü (the schema derives the v spellings
    itself). A word whose reading cannot be generated is dropped and counted.
"""

import argparse
import pathlib
import re
import sys

MIN_LENGTH = 4
# Only han characters. THUOCL rows occasionally carry latin/punctuation noise.
HAN_ONLY = re.compile(r"^[\u4e00-\u9fff]+$")
# A syllable the schema can consume: lowercase ascii only.
SYLLABLE = re.compile(r"^[a-z]+$")

HERE = pathlib.Path(__file__).resolve().parent
DICT = HERE.parent
SOURCES = HERE / "thuocl-src" / "data"
LOCK = HERE / "sources.lock"


def lock_value(key):
    for line in LOCK.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if "=" not in line:
            continue
        k, v = (part.strip() for part in line.split("=", 1))
        if k == key:
            return v
    sys.exit(f"sources.lock: no `{key}` entry")


def load_pypinyin():
    global lazy_pinyin
    try:
        import pypinyin
        from pypinyin import lazy_pinyin
    except ImportError:
        sys.exit("pypinyin missing: pip install 'pypinyin==%s'" % lock_value("thuocl-pypinyin"))
    want = lock_value("thuocl-pypinyin")
    if pypinyin.__version__ != want:
        sys.exit(
            f"pypinyin {pypinyin.__version__} != {want} pinned in sources.lock -- "
            "the phrase dictionary decides readings, so a different version "
            "changes the product"
        )


def source_words():
    words = {}
    for path in sorted(SOURCES.glob("*.txt")):
        for line in path.read_text(encoding="utf-8-sig").splitlines():
            fields = line.split("\t")
            if len(fields) != 2:
                continue
            word = fields[0].strip()
            if not HAN_ONLY.match(word) or len(word) < MIN_LENGTH:
                continue
            try:
                weight = int(fields[1].strip())
            except ValueError:
                continue
            # THUOCL has rows whose corpus count rounded to 0 (12.8k of the
            # 4+ character words). They are still real words -- keep them at
            # the 1-weight floor rather than dropping them on a comparison
            # against the default.
            if weight > words.get(word, -1):
                words[word] = weight
    return words


def known_words(path):
    """Word column of a dictionary or vocabulary product, one row per line."""
    known = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#") or line.startswith("---"):
            continue
        word = line.split("\t", 1)[0]
        if HAN_ONLY.match(word):
            known.add(word)
    return known


def readings(word):
    syllables = lazy_pinyin(word)
    if not syllables or not all(SYLLABLE.match(s) for s in syllables):
        return None
    return " ".join(syllables)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--luna", required=True, help="generated luna_pinyin.dict.yaml")
    ap.add_argument("--essay", required=True, help="generated essay.txt")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    load_pypinyin()

    candidates = source_words()
    known = known_words(pathlib.Path(args.luna)) | known_words(pathlib.Path(args.essay))
    fresh = {w: n for w, n in candidates.items() if w not in known}

    rows, dropped = [], 0
    for word in sorted(fresh, key=lambda w: (-fresh[w], w)):
        pinyin = readings(word)
        if pinyin is None:
            dropped += 1
            continue
        rows.append((word, pinyin, max(fresh[word], 1)))

    header = [
        "# Rime dictionary",
        "# encoding: utf-8",
        "#",
        "# THUOCL long-tail supplement (THUNLP/THUOCL, MIT).",
        f"# Words: THUOCL {lock_value('thuocl')[:8]}, copied verbatim under",
        "# tools/thuocl-src/. Readings: generated by pypinyin",
        f"# {lock_value('thuocl-pypinyin')} (see tools/build_thuocl.py for the filter rules).",
        "#",
        "# Read by luna_pinyin.dict.yaml via import_tables. Entries that the",
        "# luna base and essay already carry are not repeated here.",
        "---",
        "name: thuocl",
        f"version: \"{lock_value('thuocl')[:8]}\"",
        "sort: by_weight",
        "...",
    ]
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "\n".join(header + [f"{w}\t{p}\t{n}" for w, p, n in rows]) + "\n",
        encoding="utf-8",
    )
    print(
        f"{out}: {len(rows)} entries (from {len(candidates)} THUOCL words, "
        f"{len(candidates) - len(fresh)} already known, {dropped} without readings)"
    )


if __name__ == "__main__":
    main()
